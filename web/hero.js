const PLAIN = { GBA: 'Advance charcoal', GBC: 'Game Boy Color clear', GB: 'Game Boy grey' };
const SLUG = /^(?=.*[a-z])[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function heroPool(index, platform) {
  const labelled = (key) => index?.[key]?.['support-texture']?.startsWith(`${platform}/`);
  const games = GAMES[platform]
    .filter(([crc]) => labelled(crc))
    .map(([key, name, preset]) => ({ key, name, preset: preset ?? null }));
  const hacks = Object.keys(index ?? {})
    .filter((key) => SLUG.test(key) && labelled(key))
    .map((key) => ({ key, name: index[key].name ?? key, preset: null }));
  return [...games, ...hacks];
}

export function heroShell(platform, preset, presets) {
  const [, colour, finish] = presets.get(preset ?? PLAIN[platform]).split(' ');
  const outline =
    platform === 'GBA' ? 'auto' : preset === 'Pokémon Crystal' || (platform === 'GBC' && !preset) ? 'rounded' : 'notched';
  return `${outline} ${colour} ${finish}`;
}

export function heroPicks(index, random = Math.random) {
  return ['GBA', 'GBC', 'GB'].flatMap((platform) => {
    const pool = heroPool(index, platform);
    if (!pool.length) return [];
    const pick = pool[Math.floor(random() * pool.length)];
    return [{ platform, ...pick, label: index[pick.key]['support-texture'] }];
  });
}
